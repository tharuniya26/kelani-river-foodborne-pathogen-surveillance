"""Build the LaTeX manuscript from validated counts and existing analysis modules."""
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
os.environ.setdefault("OMP_NUM_THREADS", "1")

from src.statistical_analysis import interval_table, wilson_interval
from src.visualization import generate_figures, GROUPS, SITES

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "reports" / "latex"
OUTPUT = ROOT / "reports" / "computational_reanalysis_latex.pdf"


def generate_tables():
    destination = SOURCE_DIR / "generated"
    destination.mkdir(parents=True, exist_ok=True)
    data = interval_table().set_index(["pathogen", "anatomical_site"])
    lines = [r"% Generated by scripts/build_latex_report.py; do not edit by hand.",
             r"\begin{tabular}{llrrr}", r"\toprule",
             r"Reported group & Site & Positive/total & Detection (\%) & 95\% Wilson CI (\%) \\",
             r"\midrule"]
    for group_index, group in enumerate(GROUPS):
        for site_index, site in enumerate(SITES):
            row = data.loc[(group, site)]
            name = r"\textit{" + group.replace(" spp.", "") + "} spp." if site_index == 0 else ""
            lines.append(f"{name} & {site} & {int(row.positive_count)}/{int(row.total_count)} & "
                         f"{row.detection_percentage:.1f} & {100*row.wilson_low:.1f}--{100*row.wilson_high:.1f} " + r"\\")
        if group_index < len(GROUPS)-1:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (destination / "detection_intervals.tex").write_text("\n".join(lines)+"\n", encoding="utf-8")
    sensitivity = [r"\begin{tabular}{lrrr}", r"\toprule",
                   r"Source reading & Fraction & Detection (\%) & 95\% Wilson CI (\%) \\", r"\midrule"]
    for label, total in [("Abstract / report results", 27), ("Report discussion (literal)", 25)]:
        low, high = wilson_interval(22, total)
        sensitivity.append(f"{label} & 22/{total} & {2200/total:.2f} & {100*low:.2f}--{100*high:.2f} " + r"\\")
    sensitivity += [r"\bottomrule", r"\end{tabular}"]
    (destination / "denominator_sensitivity.tex").write_text("\n".join(sensitivity)+"\n", encoding="utf-8")
    interval_table().to_csv(ROOT / "data" / "processed" / "published_detection_intervals.csv", index=False)


def main():
    executable = shutil.which("pdflatex")
    if not executable:
        raise SystemExit("Install MiKTeX or TeX Live with pdflatex, then rerun python -m scripts.build_latex_report")
    generate_tables()
    generate_figures()
    with tempfile.TemporaryDirectory(prefix="kelani-latex-") as build_dir:
        for pass_number in (1, 2):
            result = subprocess.run(
                [executable, "-interaction=nonstopmode", "-halt-on-error", "-file-line-error",
                 f"-output-directory={build_dir}", "computational_reanalysis.tex"],
                cwd=SOURCE_DIR, capture_output=True, text=True, errors="replace", timeout=240)
            if result.returncode:
                raise RuntimeError(f"LaTeX pass {pass_number} failed:\n{result.stdout[-9000:]}\n{result.stderr[-1500:]}")
        log = (Path(build_dir) / "computational_reanalysis.log").read_text(errors="replace")
        issues = [line for line in log.splitlines()
                  if any(term in line for term in ("Overfull", "undefined", "Missing character", "multiply defined"))]
        if issues:
            raise RuntimeError("Review LaTeX layout/references before exporting:\n"+"\n".join(issues))
        shutil.copy2(Path(build_dir) / "computational_reanalysis.pdf", OUTPUT)
    print(f"Built {OUTPUT.name}; both LaTeX passes completed; no overflow or unresolved-reference warnings.")


if __name__ == "__main__":
    main()
